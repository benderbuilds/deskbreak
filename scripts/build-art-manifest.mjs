#!/usr/bin/env node
/**
 * Regenerates data/art-manifest.json from the art actually on disk.
 *
 * Art resolution reads this manifest, so a missing file degrades to the neutral
 * Stretch fallback instead of silently pointing at some other exercise's pose.
 * Run this after adding or removing anything in public/character/.
 *
 * `files` lists every stem in any format. `svg` and `webp` say which formats
 * each stem has. A stem can have both while a photo replaces an illustration:
 * the resolver serves the WebP and keeps the SVG as the backup if it fails.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ART_DIR = join(process.cwd(), "public", "character");
const OUT = join(process.cwd(), "data", "art-manifest.json");

const names = readdirSync(ART_DIR);
const stemsWith = (ext) =>
  names
    .filter((name) => name.endsWith(ext))
    .map((name) => name.slice(0, -ext.length))
    .sort();

const svg = stemsWith(".svg");
const webp = stemsWith(".webp");
const files = [...new Set([...svg, ...webp])].sort();

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      note: "Generated by scripts/build-art-manifest.mjs. Do not edit by hand.",
      source: "public/character",
      files,
      svg,
      webp,
    },
    null,
    2,
  )}\n`,
);

console.log(`art-manifest: ${files.length} stems (${svg.length} svg, ${webp.length} webp)`);
