#!/usr/bin/env node
/**
 * Regenerates data/art-manifest.json from the SVGs actually on disk.
 *
 * Art resolution reads this manifest, so a missing file degrades to the neutral
 * Stretch fallback instead of silently pointing at some other exercise's pose.
 * Run this after adding or removing anything in public/character/.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ART_DIR = join(process.cwd(), "public", "character");
const OUT = join(process.cwd(), "data", "art-manifest.json");

const files = readdirSync(ART_DIR)
  .filter((name) => name.endsWith(".svg"))
  .map((name) => name.slice(0, -4))
  .sort();

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      note: "Generated by scripts/build-art-manifest.mjs. Do not edit by hand.",
      source: "public/character",
      files,
    },
    null,
    2,
  )}\n`,
);

console.log(`art-manifest: ${files.length} files`);
